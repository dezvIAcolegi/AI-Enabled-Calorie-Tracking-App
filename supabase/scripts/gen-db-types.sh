#!/usr/bin/env sh
# Regenerates contracts/ts/database.ts from the shared project's public schema.
# Run after a migration lands on shared, then commit the file in the same
# /contracts PR. Never edit database.ts by hand.
#
#   sh supabase/scripts/gen-db-types.sh            (needs `supabase login`)
set -eu
REF="${SUPABASE_PROJECT_ID:-xbowjaompnlqjvoimxpa}"
OUT="contracts/ts/database.ts"
{
  echo "// GENERATED by supabase/scripts/gen-db-types.sh from the shared project's"
  echo "// public schema. Do not edit by hand; regenerate after each migration."
  echo
  npx -y supabase@latest gen types --lang=typescript --schema public --remote="$REF" 2>/dev/null
} > "$OUT.tmp"
grep -q "export type Database" "$OUT.tmp" || { echo "type generation failed" >&2; rm -f "$OUT.tmp"; exit 1; }
mv "$OUT.tmp" "$OUT"
echo "wrote $OUT"
